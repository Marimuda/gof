test_that("default dispatch supports vector attributes, functions and extra arguments", {
    x <- seq(-1,1,length.out=40); y <- 1+.4*x+sin(seq_len(40)); X <- cbind(1,x)
    m <- lm(y~x); beta <- coef(m); ic <- lava::iid(m)
    rf <- function(p,scale) scale*(y-drop(X%*%p))
    df <- function(p,scale) -scale*X
    rr <- rf(beta,2); attr(rr,"grad") <- df(beta,2)
    set.seed(511); a <- cumres(NULL,variable=x,r=rr,coef=beta,ic=ic,R=20,plots=3)
    set.seed(511); b <- cumres(NULL,variable=x,r=rf,dr=df,coef=beta,ic=ic,scale=2,R=20,plots=3)
    set.seed(511); c <- cumres(NULL,variable=x,r=rf,coef=beta,ic=ic,scale=2,R=20,plots=3)
    expect_equal(a$W,b$W); expect_equal(a$What,b$What)
    expect_equal(a$W,c$W); expect_equal(a$What,c$What,tolerance=1e-7)
    with_grad <- function(p) structure(y-drop(X%*%p),grad=-X)
    set.seed(512); a <- cumres(NULL,variable=x,r=with_grad,coef=beta,ic=ic,R=5,plots=1)
    set.seed(512); b <- cumres(NULL,variable=x,r=residuals(m),dr=-X,coef=beta,ic=ic,R=5,plots=1)
    expect_equal(a$What,b$What)
})

test_that("default and scalar helpers handle zero-parameter and degenerate statistics", {
    x <- 1:20; r <- sin(x)
    set.seed(513); g <- cumres(NULL,variable=x,r=function(p) r,coef=numeric(),R=5,plots=2)
    expect_equal(g$W[[1]],cumsum(r)/sqrt(20))
    cr <- methods::new(gof:::CumRes,r,matrix(0,20,0),matrix(0,20,0))
    scalar <- gof:::gof_samplestat(cr,R=5,x=rep(1,20))
    expect_equal(scalar$cvm,0); expect_equal(scalar$pval.cvm,1)
})

test_that("default invalid values fail at the R boundary", {
    call <- function(...) gof:::cumres.default(NULL,variable=1:4,r=1:4,dr=matrix(1,4,1),ic=matrix(1,4,1),...)
    expect_error(call(coef=Inf),"finite numeric")
    expect_error(call(coef="bad"),"finite numeric")
    expect_error(gof:::cumres.default(NULL,variable=1:4,r=letters[1:4],dr=matrix(1,4,1),ic=matrix(1,4,1),coef=NULL),"real numeric")
    expect_error(gof:::cumres.default(NULL,variable=1:4,r=1:4,dr=matrix(1i,4,1),ic=matrix(1,4,1),coef=NULL),"real numeric")
    expect_error(call(coef=NULL,breakties=NA_real_),"breakties")
    expect_error(call(coef=NULL,subset=1),"function")
    expect_error(call(coef=NULL,plots=1.5),"whole number")
    expect_error(gof:::cumres.default(NULL,variable=1:4,r=1:4,coef=1),"Supply a residual gradient")
    expect_error(call(coef=NULL,subset.max=2,subset=function(...) c(1,1)),"unique valid")
})

test_that("R bridge validates scalar and index values before unsigned conversion", {
    expect_error(gof:::.fastapprox(c(1,2),1,type=.5),"whole number")
    expect_error(gof:::.fastapprox(c(1,2),1,equal=NA),"TRUE or FALSE")
    expect_error(gof:::.clusterindex(c(1,1.5)),"integers")
    expect_error(gof:::.clusterindex(c(1,NA)),"integers")
    expect_error(gof:::.clusterindex(c(1,-1)),"integers")
    cr <- methods::new(gof:::CumRes,1:4,matrix(1,4,1),matrix(1,4,1))
    expect_no_error(cr$order(1:4))
    for (n in c(1.5,NA_real_,Inf,-1))
        expect_error(cr$samplestat(n,matrix(integer(),0,0),FALSE),"positive whole")
    expect_error(cr$sample1(matrix(.5,1,1)),"whole valid")
    expect_error(cr$sample1(matrix(NA_real_,1,1)),"whole valid")
    expect_error(cr$samplestat(1,matrix(integer(),0,0),NA),"TRUE or FALSE")
})
