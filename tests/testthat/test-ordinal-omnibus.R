test_that("ordinal omnibus statistics use the joint cutpoint process and shared draws", {
    model <- ordinal_fixture()
    set.seed(15501)
    joint <- cumres(model,variable="x",R=19,plots=3)
    set.seed(15501)
    components <- cumres(model,variable="x",aggregate="cutpoints",R=19,plots=3)
    expect_identical(joint$aggregation,"omnibus")
    expect_identical(joint$type,"ordinal-norm")
    expect_equal(joint$W[[1]],sqrt(Reduce(`+`,lapply(components$W,function(x) x^2))))
    expect_equal(joint$What[[1]],sqrt(Reduce(`+`,lapply(components$What,function(x) x^2))))
    expect_true(all(joint$W[[1]]>=0))
    expect_true(all(joint$What[[1]]>=0))
    expect_identical(as.data.frame(joint)$aggregation,rep("omnibus",2L))
    expect_identical(as.data.frame(summary(joint)),as.data.frame(joint))
    grDevices::pdf(NULL); on.exit(grDevices::dev.off(),add=TRUE)
    expect_no_error(plot(joint,legend="type2"))
    expect_match(paste(capture.output(print(joint)),collapse=" "),"Ordinal aggregation: omnibus")
})

test_that("ordinal score and cutpoint modes retain their explicit function equivalents", {
    model <- ordinal_fixture()
    set.seed(15502); score <- cumres(model,variable="x",aggregate="score",R=11,plots=2)
    set.seed(15502); legacy <- cumres(model,variable="x",aggregate=sum,R=11,plots=2)
    expect_identical(score,legacy)
    set.seed(15502); components <- cumres(model,variable="x",aggregate="cutpoints",R=11,plots=2)
    set.seed(15502); identity_result <- cumres(model,variable="x",aggregate=identity,R=11,plots=2)
    expect_identical(components,identity_result)
    expect_equal(length(components$W),length(model$up$alpha))
    expect_identical(components$aggregation,"cutpoints")
    expect_error(cumres(model,aggregate="unrecognised",R=2),"arg")
})

test_that("ordinal omnibus checks detect distribution changes that preserve the score mean", {
    d <- data.frame(x=rep(c(-1,1),each=1000),
                    y=ordered(c(rep(1:3,c(400,200,400)),rep(1:3,c(100,800,100)))))
    expect_equal(as.vector(tapply(as.numeric(d$y),d$x,mean)),c(2,2))
    model <- lava::ordreg(y~x,d,family=binomial("probit"))
    set.seed(15503); joint <- cumres(model,variable="x",R=99,plots=0)
    set.seed(15503); score <- cumres(model,variable="x",aggregate="score",R=99,plots=0)
    expect_equal(joint$KS,0)
    expect_equal(joint$CvM,0)
    expect_equal(score$KS,1)
    expect_equal(score$CvM,1)
})

test_that("binary ordinal omnibus curves are absolute versions of their one CDF process", {
    model <- ordinal_fixture(k=2)
    set.seed(15504); joint <- cumres(model,variable="x",R=11,plots=2)
    set.seed(15504); signed <- cumres(model,variable="x",aggregate="cutpoints",R=11,plots=2)
    expect_equal(joint$W[[1]],abs(signed$W[[1]]))
    expect_equal(joint$What[[1]],abs(signed$What[[1]]))
    expect_identical(joint$KS,signed$KS)
    expect_identical(joint$CvM,signed$CvM)
})
